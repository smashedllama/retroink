namespace freeink {
// Handed to the SDK through -DFREEINK_UC8253_X3_CONFIG=retroinkX3Config.
const Uc8253X3Config& retroinkX3Config() { return config(); }
}  // namespace freeink

namespace X3AnimationWaveform {
void set(const bool enabled) { config().fast = enabled ? kGameBank : stockFastBank(); }
}  // namespace X3AnimationWaveform
