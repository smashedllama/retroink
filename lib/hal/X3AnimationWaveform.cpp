const freeink::Uc8253LutBank kGameBank = {lut_vcom_game, lut_ww_game, lut_bw_game, lut_wb_game, lut_bb_game};

// The driver reads its waveforms from this object on every refresh, so
// swapping the Fast bank here takes effect on the next Fast update. It starts
// as a copy of the SDK's stock configuration, so nothing else changes.
freeink::Uc8253X3Config& config() {
  static freeink::Uc8253X3Config instance = freeink::uc8253X3DefaultConfig();
  return instance;
}

const freeink::Uc8253LutBank& stockFastBank() {
  static const freeink::Uc8253LutBank bank = freeink::uc8253X3DefaultConfig().fast;
  return bank;
}
